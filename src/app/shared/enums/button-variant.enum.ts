/** Visual variants of the `appButton` directive. Each maps to a `.btn--*` class. */
export enum ButtonVariant {
  Primary = 'primary',
  Ghost = 'ghost',
  Dark = 'dark',
  Line = 'line',
}

/** Size variants of the `appButton` directive. */
export enum ButtonSize {
  Regular = 'regular',
  Compact = 'compact',
}
